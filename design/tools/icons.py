    ("prism", "boost", "Prism", ld.polygon(3, 0.5, PI / 2) + L((-0.85, -0.05), (-0.3, -0.05)) + L((0.28, 0.0), (0.8, 0.32)) + L((0.3, -0.08), (0.82, -0.08)) + L((0.26, -0.18), (0.76, -0.46))),
