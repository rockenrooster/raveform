    ("extra_cell", "mod", "Extra Cell", ld.arc(0.72, math.radians(35), math.radians(145), 6) + L((-0.28, -0.15), (0.28, -0.15)) + L((0.0, -0.43), (0.0, 0.13))),
    ("magnet", "mod", "Magnet", magnet(0.95, 0.0)),
    ("on_beat_crit", "mod", "On-Beat Crit", L((-0.7, 0.0), (0.7, 0.0)) + L((0.0, -0.7), (0.0, 0.7)) + L((-0.38, -0.38), (0.38, 0.38)) + L((-0.38, 0.38), (0.38, -0.38))),
    ("orbitals", "riff", "Orbitals", diamond(0.0, 0.0, 0.2) + ld.arc(0.66, 0.5, 2.3, 6) + ld.arc(0.66, 0.5 + PI, 2.3 + PI, 6) + diamond(0.63, 0.19, 0.15) + diamond(-0.63, -0.19, 0.15)),
    ("pulse_ring", "riff", "Pulse Ring", ring(0.32, 12) + ring(0.7, 20)),
